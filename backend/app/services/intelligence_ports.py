"""Portas de persistência da Parte 3 (previsões, base de conhecimento, IA e PROMETHEUS)."""

from collections.abc import Sequence
from datetime import date, datetime
from typing import Any, Protocol
from uuid import UUID

from app.domain.ai_settings import AiSettings
from app.domain.prediction.equipment_risk import DeviceHistory
from app.domain.prediction.precursor_model import LabeledDetection
from app.domain.prediction.records import ModelRun, Snapshot
from app.domain.prediction.risk_model import EventWindow, Installation, Occurrence
from app.domain.prometheus.entities import (
    ActionType,
    AutonomyPolicy,
    Decision,
    DecisionStatus,
    PrometheusMode,
)


class PredictionRepository(Protocol):
    async def region_codes(self) -> list[tuple[UUID, str, str]]: ...
    async def installations(self, tz: str) -> list[Installation]: ...
    async def operational_exposure(
        self, tz: str, since: datetime
    ) -> list[tuple[str, str, date, float]]: ...
    async def occurrences(self, tz: str, since: datetime) -> list[Occurrence]: ...
    async def calendar(self, tz: str, since: datetime, until: datetime) -> list[EventWindow]: ...
    async def event_public(
        self, tz: str, since: datetime, until: datetime
    ) -> list[dict[str, Any]]: ...
    async def device_histories(self, tz: str) -> list[DeviceHistory]: ...
    async def devices_now(self, today: date) -> list[dict[str, Any]]: ...
    async def availability_by_type(self, days: int) -> dict[str, list[tuple[date, float]]]: ...
    async def equipment_with_open_preventive(self) -> set[UUID]: ...
    async def on_duty_by_region(self) -> dict[str, int]: ...
    async def handling_minutes_by_region(self, days: int) -> dict[str, float]: ...
    async def live_occurrences_by_region(self, since: datetime) -> dict[str, int]: ...
    async def telemetry_window(
        self, since: datetime, recent: datetime
    ) -> dict[UUID, dict[str, Any]]: ...
    async def open_detections(self) -> dict[UUID, tuple[int, datetime]]: ...
    async def add_detection(
        self, equipment_id: UUID, at: datetime, score: float, signals: dict[str, Any]
    ) -> None: ...
    async def close_detection(self, equipment_id: UUID, outcome: str, at: datetime) -> bool: ...
    async def expire_detections(self, older_than: datetime, at: datetime) -> list[UUID]: ...
    async def labeled_detections(self, limit: int) -> list[LabeledDetection]: ...
    async def detection_quality(self, since: datetime) -> dict[str, Any]: ...
    async def record_averted(self, equipment_id: UUID, at: datetime, intervention: str) -> None: ...
    async def averted_counts(self, since: datetime) -> dict[str, int]: ...
    async def save_model(
        self,
        kind: str,
        fitted_at: datetime,
        training_from: datetime,
        training_to: datetime,
        params: dict[str, Any],
        metrics: dict[str, Any],
    ) -> int: ...
    async def latest_model(self, kind: str) -> ModelRun | None: ...
    async def save_snapshot(
        self, kind: str, at: datetime, payload: dict[str, Any], model_id: int | None
    ) -> None: ...
    async def get_snapshot(self, kind: str) -> Snapshot | None: ...


class KnowledgeRepository(Protocol):
    async def lexemes(self, texts: Sequence[str]) -> list[list[str]]: ...
    async def list_documents(self) -> list[dict[str, Any]]: ...
    async def get_document(self, document_id: UUID) -> dict[str, Any] | None: ...
    async def find_by_slug(self, slug: str) -> tuple[UUID, str] | None: ...
    async def upsert_document(
        self,
        *,
        slug: str,
        title: str,
        doc_type: str,
        metadata: dict[str, Any],
        content: str,
        content_hash: str,
        source: str,
        updated_by: UUID | None,
        at: datetime,
    ) -> UUID: ...
    async def replace_chunks(self, document_id: UUID, chunks: Sequence[dict[str, Any]]) -> None: ...
    async def delete_document(self, document_id: UUID) -> bool: ...
    async def version(self) -> str: ...
    async def all_lexemes(self) -> list[tuple[int, list[str]]]: ...
    async def vector_search(
        self, column: str, vector: Sequence[float], limit: int, model: str | None = None
    ) -> list[tuple[int, float]]: ...
    async def chunks(self, ids: Sequence[int]) -> dict[int, dict[str, Any]]: ...
    async def chunks_for_provider(self) -> list[tuple[int, str]]: ...
    async def set_provider_embeddings(
        self, items: Sequence[tuple[int, list[float]]], model: str | None
    ) -> None: ...
    async def clear_provider_embeddings(self) -> None: ...


class AiRepository(Protocol):
    async def get_settings(self) -> AiSettings: ...
    async def save_settings(self, settings: AiSettings) -> None: ...
    async def add_usage(
        self,
        *,
        at: datetime,
        provider: str,
        model: str,
        feature: str,
        input_tokens: int,
        output_tokens: int,
        cost_usd: float,
        ok: bool,
        error: str | None,
    ) -> None: ...
    async def usage_since(self, since: datetime) -> tuple[int, int]: ...
    async def usage_by_day(self, since: datetime, tz: str) -> list[dict[str, Any]]: ...


class PrometheusRepository(Protocol):
    async def mode(self) -> tuple[PrometheusMode, int]: ...
    async def set_mode(
        self, mode: PrometheusMode, ttl_minutes: int, actor_id: UUID, at: datetime
    ) -> None: ...
    async def policies(self) -> list[AutonomyPolicy]: ...
    async def save_policy(self, policy: AutonomyPolicy, actor_id: UUID, at: datetime) -> None: ...
    async def add_decision(self, decision: Decision) -> None: ...
    async def update_decision(self, decision: Decision) -> None: ...
    async def get_decision(
        self, decision_id: UUID, *, for_update: bool = False
    ) -> Decision | None: ...
    async def list_decisions(
        self, statuses: Sequence[DecisionStatus] | None, limit: int
    ) -> list[Decision]: ...
    async def recently_handled(self, situation_key: str, since: datetime) -> bool: ...
    async def auto_executed_since(self, action: ActionType, since: datetime) -> int: ...
    async def expired_pending(self, now: datetime) -> list[Decision]: ...
    async def stats(self, since: datetime) -> dict[str, Any]: ...
