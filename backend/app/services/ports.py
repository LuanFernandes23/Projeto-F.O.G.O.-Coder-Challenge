class UnitOfWork(Protocol):
    """Repositórios expostos como somente leitura (permite implementações covariantes)."""

    @property
    def users(self) -> UserRepository: ...
    @property
    def organizations(self) -> OrganizationRepository: ...
    @property
    def regions(self) -> RegionRepository: ...
    @property
    def equipment_types(self) -> EquipmentTypeRepository: ...
    @property
    def equipment(self) -> EquipmentRepository: ...
    @property
    def equipment_history(self) -> EquipmentStatusHistoryRepository: ...
    @property
    def maintenance_plans(self) -> MaintenancePlanRepository: ...
    @property
    def maintenance_orders(self) -> MaintenanceOrderRepository: ...
    @property
    def agents(self) -> AgentRepository: ...
    @property
    def agent_history(self) -> AgentStatusHistoryRepository: ...
    @property
    def job_locks(self) -> JobLockRepository: ...
    @property
    def alerts(self) -> AlertRepository: ...
    @property
    def dispatches(self) -> DispatchRepository: ...
    @property
    def telemetry(self) -> TelemetryRepository: ...
    @property
    def operations(self) -> OperationsRepository: ...
    @property
    def events(self) -> EventPublisher: ...
    @property
    def predictions(self) -> PredictionRepository: ...
    @property
    def knowledge(self) -> KnowledgeRepository: ...
    @property
    def ai(self) -> AiRepository: ...
    @property
    def prometheus(self) -> PrometheusRepository: ...

    async def __aenter__(self) -> Self: ...
    async def __aexit__(
        self,
        exc_type: type[BaseException] | None,
        exc: BaseException | None,
        tb: TracebackType | None,
    ) -> None: ...
    async def commit(self) -> None: ...
    async def rollback(self) -> None: ...
